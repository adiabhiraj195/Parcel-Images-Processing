"""Unit tests for OCR and Barcode adapters."""

import numpy as np
import zxingcpp

from app.pipeline.interfaces import OcrTextBox
from app.pipeline.ocr import MockOcrEngine, TesseractOcrEngine, PaddleOcrEngine, LocalCpuOcrEngine, get_ocr_engine
from app.pipeline.barcode import ZXingBarcodeDecoder, MockBarcodeDecoder


def test_mock_ocr_structured_output():
    """Verify OCR returns structured text, geometry quad, and confidence scores."""
    engine = MockOcrEngine()
    canvas = np.zeros((300, 300, 3), dtype=np.uint8)
    res = engine.extract_text(canvas, variant_label="upscaled_2x", source_crop="overlay_top_left")

    assert res.engine.startswith("mock-ocr")
    assert res.model_version is not None
    assert res.source_crop == "overlay_top_left"
    assert res.preprocessing_variant == "upscaled_2x"
    assert len(res.lines) >= 4
    assert any("AWB" in line.text for line in res.lines)
    assert any(line.score > 0.9 for line in res.lines)
    assert len(res.lines[0].box) == 4
    # Confidences must not be hardcoded to identical constants
    scores = [l.score for l in res.lines]
    assert len(set(scores)) > 1


