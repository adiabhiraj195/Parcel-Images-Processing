def test_paddleocr_inference_and_no_silent_trocr_fallback():
    """Verify PaddleOCR runs genuine PaddleOCR on Apple Silicon and never silently delegates to TrOCR."""
    import pytest
    engine = PaddleOcrEngine()
    health = engine.get_health()
    assert health["engine"] == "paddleocr"
    assert health["readiness"] == "ready"
    assert health["model_version"].startswith("PP-OCRv")

    canvas = np.zeros((100, 200, 3), dtype=np.uint8)
    res = engine.extract_text(canvas, variant_label="upscaled", source_crop="yellow_dws")

    assert res is not None
    assert res.preprocessing_variant == "upscaled"
    assert res.source_crop == "yellow_dws"
    # Result MUST come from paddleocr, NEVER silently from local_cpu
    assert res.engine == "paddleocr"
    assert res.engine != "local_cpu"

    # Verify degraded behavior: if OCR is unavailable, prevent silent fallback with unintended engine
    engine._is_ready = False
    engine._error = "Paddle runtime simulated unavailable"
    degraded_health = engine.get_health()
    assert degraded_health["readiness"] == "degraded"
    assert "simulated unavailable" in degraded_health["error"]

    with pytest.raises(RuntimeError, match="Silent processing with an unintended engine is prevented"):
        engine.extract_text(canvas)


def test_zxing_barcode_decoder():
    """Verify barcode decoding on a barcode generated by zxingcpp."""
    barcode_val = "TRACK9876543210"
    barcode_obj = zxingcpp.create_barcode(barcode_val, zxingcpp.BarcodeFormat.Code128)
    zxing_img = zxingcpp.write_barcode_to_image(barcode_obj)
    image_arr = np.array(zxing_img, dtype=np.uint8)

    decoder = ZXingBarcodeDecoder()
    decoded_list = decoder.decode(image_arr)

    assert len(decoded_list) >= 1
    assert decoded_list[0].raw_value == barcode_val
    assert "Code128" in decoded_list[0].symbology


